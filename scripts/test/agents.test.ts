import { test } from 'node:test';
import assert from 'node:assert/strict';
import { generateAgentsMd } from '../build-agents.ts';
import type { Rule, Section, SkillMetadata } from '../build-agents.ts';

const metadata: SkillMetadata = {
  title: 'NestJS Best Practices',
  version: '1.2.0',
  organization: 'NestJS Best Practices',
  date: 'October 2026',
  abstract: 'Test abstract.',
  references: ['https://docs.nestjs.com', 'https://github.com/nestjs/nest'],
};

const sections: Section[] = [
  { number: 1, name: 'Architecture', prefix: 'arch-', impact: 'CRITICAL', description: 'desc' },
  { number: 2, name: 'Database & ORM', prefix: 'db-', impact: 'MEDIUM-HIGH', description: 'desc' },
  { number: 3, name: 'Empty Section', prefix: 'empty-', impact: 'LOW', description: 'desc' },
];

function makeRule(
  filename: string,
  title: string,
  impact: string,
  section: Section,
  body: string,
  impactDescription?: string,
): Rule {
  return {
    filename,
    frontmatter: { title, impact, impactDescription },
    content: `## ${title}\n\n**Impact: ${impact}**${impactDescription ? ` — ${impactDescription}` : ''}\n\n${body}`,
    section,
    ruleNumber: '',
  };
}

const rules: Rule[] = [
  makeRule('arch-1.md', 'Rule One', 'CRITICAL', sections[0], 'alpha body', 'important'),
  makeRule('arch-2.md', 'Rule Two', 'HIGH', sections[0], 'beta body'),
  makeRule('db-1.md', 'Db Rule', 'MEDIUM', sections[1], 'gamma body'),
];

test('generateAgentsMd builds header, abstract, note', () => {
  const out = generateAgentsMd(rules, metadata, sections);
  assert.ok(out.includes('# NestJS Best Practices\n'));
  assert.ok(out.includes('**Version 1.2.0**\n'));
  assert.ok(out.includes('NestJS Best Practices\n'));
  assert.ok(out.includes('October 2026\n'));
  assert.ok(out.includes('This document is mainly for agents and LLMs'));
  assert.ok(out.includes('## Abstract\n\nTest abstract.\n'));
});

test('generateAgentsMd builds TOC with anchors and special-char slugs', () => {
  const out = generateAgentsMd(rules, metadata, sections);
  assert.ok(out.includes('1. [Architecture](#1-architecture) — **CRITICAL**\n'));
  assert.ok(out.includes('   - 1.1 [Rule One](#11-rule-one)\n'));
  assert.ok(out.includes('   - 1.2 [Rule Two](#12-rule-two)\n'));
  assert.ok(out.includes('2. [Database & ORM](#2-database--orm) — **MEDIUM-HIGH**\n'));
  assert.ok(out.includes('   - 2.1 [Db Rule](#21-db-rule)\n'));
});

test('generateAgentsMd numbers rules and strips body heading + impact line', () => {
  const out = generateAgentsMd(rules, metadata, sections);
  assert.ok(out.includes('### 1.1 Rule One\n\n**Impact: CRITICAL** — important\n\nalpha body\n'));
  assert.ok(out.includes('### 1.2 Rule Two\n\n**Impact: HIGH**\n\nbeta body\n'));
  assert.ok(out.includes('### 2.1 Db Rule\n\n**Impact: MEDIUM**\n\ngamma body\n'));
  assert.ok(!out.includes('## Rule One'));
});

test('generateAgentsMd strips body heading on CRLF rule content and normalizes to LF', () => {
  const crlfRule: Rule = {
    filename: 'arch-crlf.md',
    frontmatter: { title: 'Crlf Rule', impact: 'HIGH' },
    content: '## Crlf Rule\r\n\r\n**Impact: HIGH**\r\n\r\ncrlf body\r\n',
    section: sections[0],
    ruleNumber: '',
  };
  const out = generateAgentsMd([crlfRule], metadata, sections);
  assert.ok(out.includes('### 1.1 Crlf Rule\n\n**Impact: HIGH**\n\ncrlf body\n'));
  assert.ok(!out.includes('\r'), 'output should contain no carriage returns');
});

test('anchors match GitHub for headings with dashes, slashes and ampersands', () => {
  // github-slugger drops punctuation WITHOUT collapsing the spaces it leaves behind, so a spaced
  // em dash or a slash produces two adjacent hyphens. The generator must do the same or its TOC
  // links do not resolve on GitHub.
  const emDash = makeRule(
    'arch-dash.md',
    'Scope Covers the User Only — Every Other Dimension',
    'HIGH',
    sections[0],
    'body',
  );
  const slash = makeRule('arch-slash.md', 'Option E — Transport / CDN SWR', 'HIGH', sections[0], 'body');
  const out = generateAgentsMd([emDash, slash], metadata, sections);
  assert.ok(out.includes('#11-scope-covers-the-user-only--every-other-dimension'), out);
  assert.ok(out.includes('#12-option-e--transport--cdn-swr'), out);
});

test('generateAgentsMd omits empty sections', () => {
  const out = generateAgentsMd(rules, metadata, sections);
  assert.ok(!out.includes('## 3. Empty Section'));
  assert.ok(!out.includes('3. [Empty Section]'));
});

test('generateAgentsMd renders references footer and deterministic trailer', () => {
  const out = generateAgentsMd(rules, metadata, sections);
  assert.ok(out.includes('## References\n\n- https://docs.nestjs.com\n- https://github.com/nestjs/nest\n'));
  assert.ok(out.includes('*Generated by build-agents.ts from `rules/`'));
  assert.ok(!/\d{4}-\d{2}-\d{2}/.test(out), 'the footer must not contain a volatile date');
});
